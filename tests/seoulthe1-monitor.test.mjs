const kw = [
  ['키워드', '그룹', '추천', '진단', '현재 입찰가(원)', '추천 입찰가(원)', '목표순위', '상한(원)', '평균순위', '전주 순위', '노출', '클릭', 'CTR', '비용(원, VAT 별도)', 'CPC(원)', '1위 평균입찰가(원)', '근거'],
  ['판교신경외과', '1 지역 핵심', '상향', '순위 미달(클릭 있음)', '300', '360', '6', '800', '6.4', '5.3', '20', '2', '10.0%', '154', '77', '5,530', '평균순위 6.4 > 목표 6위, 클릭 2'],
];

test('대시보드 시트 값을 화면용 구조로 바꾼다', () => {
  const d = parseDashboard(dash, kw);
  assert.equal(d.period.start, '2026-11-13');
  assert.equal(d.metrics.length, 8);
  assert.deepEqual(d.metrics[0], { label: '노출', cur: '230', prev: '200', change: '15.0%' });
  assert.equal(d.alerts.length, 7);
  assert.equal(d.alerts.filter((a) => a.status === '알림').length, 3);
  assert.equal(d.alertCount, '3');
  assert.deepEqual(d.recs.map((r) => r.action), ['상향', '하향', 'OFF', '보류', '유지']);
  assert.equal(d.keywords[0].keyword, '판교신경외과');
  assert.equal(d.keywords[0].proposed, '360');
});

test('빈 시트에서도 오류 없이 빈 구조를 돌려준다', () => {
  const d = parseDashboard([], []);
  assert.equal(d.metrics.length, 0);
  assert.equal(d.keywords.length, 0);
});
